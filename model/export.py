"""The "compiler": trained model -> chip configuration + test files.

Run from the repo's top folder:  python model/export.py   (after train.py)
Reads  model/build/model.json
Writes firmware/bnn_weights.h   C header for the host microcontroller
       test/test_vectors.json   inputs + expected outputs for the cocotb test
"""
import json
from pathlib import Path

from reference import bias_to_threshold, neuron

MODEL_DIR = Path(__file__).resolve().parent
ROOT = MODEL_DIR.parent


def main():
    with open(MODEL_DIR / "build" / "model.json") as f:
        model = json.load(f)

    w_byte = model["w_byte"]
    threshold = bias_to_threshold(model["b_int"])
    assert 0 <= w_byte <= 0xFF and 0 <= threshold <= 9

    # Check 1: the integer reference model must agree with PyTorch on all
    # 256 inputs. If this fails, the threshold folding or bit order is wrong.
    vectors = []
    for x in range(256):
        y, pc = neuron(x, w_byte, threshold)
        assert y == model["torch_preds"][x], (
            f"reference and PyTorch disagree on input {x:08b}: ref {y}, torch {model['torch_preds'][x]}"
        )
        vectors.append({"x": x, "pc": pc, "y": y})
    print(f"reference model matches PyTorch on all 256 inputs  (W={w_byte:08b}, T={threshold})")

    # The configuration "bitstream": 2 bytes in the order SPEC.md section 5 gives.
    bitstream = [w_byte, threshold]

    header = f"""// Generated by model/export.py. Do not edit by hand.
#ifndef BNN_WEIGHTS_H
#define BNN_WEIGHTS_H

#include <stdint.h>

// Mode values driven on uio_in[1:0] (SPEC.md section 4)
#define BNN_MODE_RUN    0u
#define BNN_MODE_LOAD_W 1u
#define BNN_MODE_LOAD_T 2u

// Trained model: weight bit i is input i (1 = +1, 0 = -1)
#define BNN_WEIGHTS   0x{w_byte:02X}u  // 0b{w_byte:08b}
#define BNN_THRESHOLD {threshold}u

// Configuration bitstream, sent in this order: {{weights, threshold}}
static const uint8_t bnn_bitstream[{len(bitstream)}] = {{ {", ".join(f"0x{b:02X}" for b in bitstream)} }};
static const uint8_t bnn_bitstream_modes[{len(bitstream)}] = {{ BNN_MODE_LOAD_W, BNN_MODE_LOAD_T }};

#endif
"""
    with open(ROOT / "firmware" / "bnn_weights.h", "w") as f:
        f.write(header)

    # One test vector per line, so the file is easy to read and to diff.
    lines = [f'  {{"x": {v["x"]}, "pc": {v["pc"]}, "y": {v["y"]}}}' for v in vectors]
    with open(ROOT / "test" / "test_vectors.json", "w") as f:
        f.write(f'{{"w_byte": {w_byte}, "threshold": {threshold}, "vectors": [\n')
        f.write(",\n".join(lines))
        f.write("\n]}\n")

    print("wrote firmware/bnn_weights.h and test/test_vectors.json")


if __name__ == "__main__":
    main()
